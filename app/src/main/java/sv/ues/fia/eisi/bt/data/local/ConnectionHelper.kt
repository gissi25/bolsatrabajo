    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) {
        Log.d(TAG, "Actualizando BD de versión $oldVersion a $newVersion")
        db.execSQL("PRAGMA foreign_keys = OFF;")
        dropAllTables(db)
        db.execSQL("PRAGMA foreign_keys = ON;")
        onCreate(db)
    }

